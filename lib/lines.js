// 某站可以换乘哪些线路（同名站出现在多条线路上即视为换乘站）
export function transfersAt(station, lineId) {
  return LINES.filter((l) => l.id !== lineId && l.stations.includes(station)).map(
    (l) => l.name
  );
}

// 由字符串生成稳定的伪随机数，保证同一段区间每次长度一样（双人对战才公平）
function hash(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0) / 4294967296;
}

// 生成一趟行程：stops 个停靠站
export function buildTrip(line, startIndex, dir, stops) {
  const lv = LEVELS[line.level];
  const names = [];
  for (let i = 0; i <= stops; i++) names.push(line.stations[startIndex + dir * i]);
  const segs = [];
  for (let i = 0; i < stops; i++) {
    const r = hash(line.id + names[i] + names[i + 1]);
    // 真实站间距：dist[k] 是第 k 站到第 k+1 站
    const k = dir > 0 ? startIndex + i : startIndex - i - 1;
    const len = line.dist[k];
    let limit = null;
    if (lv.limit && hash(names[i + 1] + line.id) > 0.45) {
      const from = Math.round(len * 0.3);
      limit = { from, to: from + 130, kmh: 50 };
    }
    // 以下全部按线路和区间算出来（不用随机数），每日挑战大家碰到的都一样
    const h = (tag) => hash(`${line.id}|${names[i]}|${names[i + 1]}|${tag}`);
    // 区间小事件：乘客紧急呼叫 / 前方施工人员鸣笛 / 临时施工限速
    let event = null;
    if (h("ev") < 0.55) {
      let type = ["intercom", "horn", "work"][Math.floor(h("evtype") * 3)];
      if (type === "work" && limit) type = "horn";
      const want = len * (0.3 + 0.3 * h("evpos"));
      const at = Math.round(Math.min(len - 320, Math.max(180, want)));
      event = { type, at };
      if (type === "work") {
        // 播报后 250 米才进施工区，留足减速距离；施工区不能和车站挤在一起
        const zone = { from: at + 250, to: at + 430, kmh: 40 };
        if (zone.to > len - 250) event = { type: "horn", at };
        else event.zone = zone;
      }
    }
    const late = h("late") < 0.4; // 开门后有没有乘客最后一刻跑来
    segs.push({ from: names[i], to: names[i + 1], len, limit, door: r > 0.5 ? "左" : "右", event, late });
  }
  return { names, segs, terminal: dir > 0 ? line.stations[line.stations.length - 1] : line.stations[0] };
}

